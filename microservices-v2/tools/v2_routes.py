"""Build the v2 gateway route table from the monolith itself (self-contained; no stage-1 files needed).

    python microservices-v2/tools/v2_routes.py            # write gateway/gateway_app/routes.json + docs/ENDPOINT_INVENTORY.md
    python microservices-v2/tools/v2_routes.py --check    # exit 1 when stale or when a route has no owner / two owners

1. Imports the monolith (``app.main``; import only) and lists every route in FastAPI's evaluation order
   (first full match wins), which is the order the gateway uses.
2. Assigns each route to the service owning the ``include_router`` call that produced it
   (``tools/ownership.json``: position, module, router attribute, prefix).
3. Applies ``tools/route_overrides.json`` (routes whose data moved to another service in v2).
"""
from __future__ import annotations

import collections
import importlib
import json
import os
import sys
from pathlib import Path

V2 = Path(__file__).resolve().parents[1]
REPO = V2.parent
OUT = V2 / "gateway" / "gateway_app" / "routes.json"
DOC = V2 / "docs" / "ENDPOINT_INVENTORY.md"
APP_LEVEL = {"/health": "identity", "/docs": "identity", "/api/docs": "identity", "/redoc": "identity", "/api/redoc": "identity",
             "/openapi.json": "identity", "/api/openapi.json": "identity"}  # answered by the gateway itself (docs snapshot)


def _flatten(routes):
    try:
        from fastapi.routing import _iter_routes_with_context
        return [((ctx.path if ctx else getattr(r, "path", None)), sorted((ctx.methods if ctx else getattr(r, "methods", None)) or []),
                 (ctx.endpoint if ctx else getattr(r, "endpoint", None))) for r, ctx in _iter_routes_with_context(routes)]
    except ImportError:
        return [(getattr(r, "path", None), sorted(getattr(r, "methods", None) or []), getattr(r, "endpoint", None)) for r in routes]


def build():
    for k, v in {"DATABASE_URL": "sqlite:///./_routes_unused.db", "SECRET_KEY": "x", "GOOGLE_CLIENT_ID": "x", "GOOGLE_CLIENT_SECRET": "x",
                 "GOOGLE_REDIRECT_URI": "x", "email_user": "x", "email_pass": "x", "LOG_LEVEL": "WARNING"}.items():
        os.environ.setdefault(k, v)
    sys.path.insert(0, str(REPO))
    import app.main as monolith
    from fastapi import FastAPI

    ownership = json.loads((V2 / "tools" / "ownership.json").read_text(encoding="utf-8"))
    overrides = json.loads((V2 / "tools" / "route_overrides.json").read_text(encoding="utf-8"))["routes"]
    owner_of = collections.defaultdict(list)
    for m in ownership["mounts"]:
        try:
            mod = importlib.import_module(f"app.api.v1.endpoints.{m['module']}")
        except ModuleNotFoundError:
            continue  # a v2-only module (e.g. search_events): its routes are assigned by route_overrides.json
        probe = FastAPI()
        probe.include_router(getattr(mod, m["attr"]), prefix="/api/v1" + m["prefix"])
        for path, methods, endpoint in _flatten(probe.routes):
            owner_of[(path, tuple(methods), id(endpoint))].append(m["service"])
    rows, errors = [], []
    for index, (path, methods, endpoint) in enumerate(_flatten(monolith.app.routes)):
        if path in APP_LEVEL:
            svc = APP_LEVEL[path]
        else:
            owners = sorted(set(owner_of.get((path, tuple(methods), id(endpoint)), [])))
            if len(owners) != 1:
                errors.append(f"{methods} {path}: owners {owners}")
            svc = owners[0] if owners else None
        svc = overrides.get(path, svc)
        rows.append({"index": index, "path": path, "methods": methods, "service": svc,
                     "endpoint": f"{getattr(endpoint, '__module__', '?')}.{getattr(endpoint, '__name__', '?')}"})
    return rows, errors


def render(rows):
    table = {"generated_from": "app.main:app (monolith) + tools/ownership.json + tools/route_overrides.json",
             "socketio_owner": "communication", "default_service": "identity",
             "routes": [{k: r[k] for k in ("index", "path", "methods", "service")} for r in rows]}
    counts = collections.Counter(r["service"] for r in rows)
    md = ["# Endpoint inventory (v2)", "", "Generated by `python microservices-v2/tools/v2_routes.py` from the monolith's own route table, in the",
          "order FastAPI evaluates routes (the gateway uses the same order).", "", "| Service | Routes |", "|---|---|"]
    md += [f"| {s} | {n} |" for s, n in sorted(counts.items())] + [f"| **total** | **{len(rows)}** |", "",
                                                                     "| # | Methods | Path | Service | Monolith handler |", "|---|---|---|---|---|"]
    md += [f"| {r['index']} | {', '.join(m for m in r['methods'] if m != 'HEAD') or '-'} | `{r['path']}` | {r['service']} | `{r['endpoint']}` |" for r in rows]
    return json.dumps(table, indent=1) + "\n", "\n".join(md) + "\n"


if __name__ == "__main__":
    rows, errors = build()
    routes_text, doc_text = render(rows)
    if errors:
        print("ownership errors:\n  " + "\n  ".join(errors))
    if "--check" in sys.argv:
        stale = OUT.read_text(encoding="utf-8") != routes_text
        print("routes.json stale" if stale else "routes.json current")
        sys.exit(1 if (stale or errors) else 0)
    OUT.write_text(routes_text, encoding="utf-8")
    DOC.write_text(doc_text, encoding="utf-8")
    print(f"{len(rows)} routes written; errors: {len(errors)}")

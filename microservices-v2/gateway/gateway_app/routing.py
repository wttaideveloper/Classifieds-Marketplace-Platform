"""Decides which service handles a request, with the monolith's exact precedence.

The table (``routes.json``) is the monolith's own route list in evaluation order, generated by
``tools/generate_inventory.py``. Matching reproduces Starlette/FastAPI:

1. the first route whose path AND method match wins (FULL match);
2. otherwise the first route whose path matches with another method (PARTIAL) -> its service
   answers 405 with the same ``Allow`` header as the monolith;
3. otherwise, when the path with/without a trailing slash matches a route, that route's service
   answers (it issues the same 307 redirect the monolith would);
4. otherwise the default service answers (404 ``{"detail": "Not Found"}``, CORS preflight, ...).

Socket.IO (``SOCKETIO_PATH``) goes to the service that runs the Socket.IO server, exactly like the
monolith's ``socketio.ASGIApp`` wrapper, which intercepts that prefix before FastAPI routing.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from starlette.routing import compile_path

ROUTES_FILE = Path(__file__).with_name("routes.json")


@dataclass(frozen=True)
class RouteEntry:
    index: int
    path: str
    methods: frozenset[str]
    service: str
    regex: object
    convertors: dict


@dataclass(frozen=True)
class RouteDecision:
    service: str
    kind: str  # "full" | "partial" | "redirect_slash" | "default" | "socketio"
    route_path: str | None = None


def normalize_socketio_path(path: str | None, *, environment: str = "development", standalone: bool = False) -> str:
    """Same rule as ``Settings.resolve_socketio_path`` in the monolith."""
    normalized = (path or "/socket.io").strip()
    if not normalized.startswith("/"):
        normalized = f"/{normalized}"
    normalized = normalized.rstrip("/") or "/socket.io"
    if environment == "production" and not standalone and normalized == "/socket.io":
        return "/api/socket.io"
    return normalized


class RouteTable:
    def __init__(self, entries: list[RouteEntry], *, default_service: str, socketio_service: str, socketio_path: str):
        self.entries = entries
        self.default_service = default_service
        self.socketio_service = socketio_service
        # python-engineio intercepts paths starting with "/<engineio_path>/".
        self.socketio_prefix = socketio_path.rstrip("/") + "/"

    @classmethod
    def load(cls, path: Path = ROUTES_FILE, *, socketio_path: str = "/socket.io") -> "RouteTable":
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        entries = []
        for row in data["routes"]:
            regex, _fmt, convertors = compile_path(row["path"])
            entries.append(
                RouteEntry(
                    index=row["index"],
                    path=row["path"],
                    methods=frozenset(m.upper() for m in row["methods"]),
                    service=row["service"],
                    regex=regex,
                    convertors=convertors,
                )
            )
        entries.sort(key=lambda e: e.index)
        return cls(
            entries,
            default_service=data.get("default_service", "identity"),
            socketio_service=data.get("socketio_owner", "communication"),
            socketio_path=socketio_path,
        )

    @property
    def services(self) -> set[str]:
        return {e.service for e in self.entries} | {self.default_service, self.socketio_service}

    @staticmethod
    def _path_matches(entry: RouteEntry, path: str) -> bool:
        match = entry.regex.match(path)
        if not match:
            return False
        # Starlette converts parameters after matching; a value its convertor rejects is no match.
        for key, value in match.groupdict().items():
            try:
                entry.convertors[key].convert(value)
            except Exception:  # noqa: BLE001
                return False
        return True

    def _match(self, path: str, method: str) -> tuple[str, RouteEntry] | None:
        partial: RouteEntry | None = None
        for entry in self.entries:
            if not self._path_matches(entry, path):
                continue
            if not entry.methods or method in entry.methods:
                return "full", entry
            if partial is None:
                partial = entry
        if partial is not None:
            return "partial", partial
        return None

    def resolve(self, path: str, method: str, scope_type: str = "http") -> RouteDecision:
        if path.startswith(self.socketio_prefix):
            return RouteDecision(self.socketio_service, "socketio")
        if scope_type == "websocket":
            # The monolith has no other WebSocket endpoint: the default service closes it the same way.
            return RouteDecision(self.default_service, "default")
        found = self._match(path, method.upper())
        if found:
            kind, entry = found
            return RouteDecision(entry.service, kind, entry.path)
        if path != "/":
            alternate = path[:-1] if path.endswith("/") else path + "/"
            found = self._match(alternate, method.upper())
            if found:
                return RouteDecision(found[1].service, "redirect_slash", found[1].path)
        return RouteDecision(self.default_service, "default")
